//! BN254 constants, in one place for `groth16_verifier` and `policy_registry`
//! (#10, #11, #231). Values from EIP-197 / CAP-0074.

use soroban_sdk::{Bytes, Env, U256};

/// r, the order of the scalar field, big-endian. A public signal or a policy
/// commitment is an element of this field and must be `< r`.
pub const SCALAR_FIELD: [u8; 32] = [
    0x30, 0x64, 0x4e, 0x72, 0xe1, 0x31, 0xa0, 0x29, 0xb8, 0x50, 0x45, 0xb6, 0x81, 0x81, 0x58, 0x5d,
    0x28, 0x33, 0xe8, 0x48, 0x79, 0xb9, 0x70, 0x91, 0x43, 0xe1, 0xf5, 0x93, 0xf0, 0x00, 0x00, 0x01,
];

/// p, the modulus of the base field, big-endian. A point coordinate is `< p`.
pub const BASE_FIELD: [u8; 32] = [
    0x30, 0x64, 0x4e, 0x72, 0xe1, 0x31, 0xa0, 0x29, 0xb8, 0x50, 0x45, 0xb6, 0x81, 0x81, 0x58, 0x5d,
    0x97, 0x81, 0x6a, 0x91, 0x68, 0x71, 0xca, 0x8d, 0x3c, 0x20, 0x8c, 0x16, 0xd8, 0x7c, 0xfd, 0x47,
];

pub fn scalar_field(env: &Env) -> U256 {
    U256::from_be_bytes(env, &Bytes::from_array(env, &SCALAR_FIELD))
}

pub fn base_field(env: &Env) -> U256 {
    U256::from_be_bytes(env, &Bytes::from_array(env, &BASE_FIELD))
}

/// True when `value` is a canonical scalar (`< r`).
pub fn is_scalar(env: &Env, value: &U256) -> bool {
    *value < scalar_field(env)
}
